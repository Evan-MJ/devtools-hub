// Regenerate the three static fallback files (sitemap.xml, llms.txt, llms-full.txt)
// from the REAL Cloudflare Functions, so a "Function fails to compile" deploy falls
// back to bytes that match what the Function would serve — not a months-old snapshot.
//
// Why: the fallback files are the standing policy for anything that must survive a
// function not compiling (AGENTS.md), but they only refresh by hand, so sitemap.xml /
// llms.txt sat at 2026-10-01 and llms-full.txt at 2026-07-22 while the site grew
// 208 → 357 tools. A broken Function deploy would have served a sitemap covering half
// the site and an llms.txt catalog counting the wrong tool population.
// Same mechanism as gen-tool-dates.js: runs on every deploy via scripts/pre-deploy.sh.
//
// How: executes functions/{sitemap.xml,llms.txt,llms-full.txt}.js in Node with a
// disk-backed ASSETS stub (same runtime model as bug349-page-md-gate.js), writes the
// output to the tree, and asserts the regenerated bytes are complete:
//   - every manifest slug appears in its regenerated file
//   - sitemap URL set == manifest tool set + 11 categories + top pages
//   - llms-full.txt tool entries == manifest row count
// A generator that cannot read manifest.txt is a 500 ans instead of a regression —
// the asserts below turn that into a loud exit code, and pre-deploy.sh aborts on it.
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const ROOT = path.resolve(import.meta.dirname, '..');

globalThis.caches = { default: { match: async () => undefined, put: async () => {} } };

function makeAssets() {
  return {
    async fetch(u) {
      const rel = new URL(u).pathname.replace(/^\//, '') || 'index.html';
      const cands = [rel, rel.replace(/\/$/, '') + '/index.html', rel + 'index.html'];
      for (const c of cands) {
        if (c.endsWith('/') || c === '') continue;
        if (fs.existsSync(path.join(ROOT, c))) {
          return new Response(fs.readFileSync(path.join(ROOT, c), 'utf8'), { status: 200 });
        }
      }
      // No static file: Pages serves the SPA index.html fallback (BUG-303 trap).
      for (const c of ['index.html', '../index.html']) {
        if (fs.existsSync(path.join(ROOT, c))) {
          return new Response(fs.readFileSync(path.join(ROOT, c), 'utf8'), {
            status: 200,
            headers: { 'X-Spa-Fallback': '1' },
          });
        }
      }
      return new Response('', { status: 404 });
    },
  };
}

async function runFn(rel) {
  const mod = await import(pathToFileURL(path.join(ROOT, rel)).href + '?t=' + Date.now());
  const res = await mod.onRequest({
    params: {},
    request: new Request('https://tools.scoreroute.com/' + rel.replace('functions/', '')),
    next: async () => new Response('NEXT', { status: 404 }),
    env: { ASSETS: makeAssets() },
  });
  const body = await res.text();
  if (res.status !== 200) throw new Error(rel + ' returned ' + res.status + ': ' + body.slice(0, 200));
  return body;
}

const manifest = fs.readFileSync(path.join(ROOT, 'manifest.txt'), 'utf8');
const slugs = manifest
  .split('\n')
  .map((l) => l.trim())
  .filter((l) => l && !l.startsWith('#'))
  .map((l) => l.split('|')[0].trim())
  .filter((s) => s && !s.includes(' '));
if (slugs.length < 10) throw new Error('manifest parsed to only ' + slugs.length + ' slugs');
const last = slugs[slugs.length - 1];

// Which outputs to regenerate. Default: all three. `node scripts/regen-static-fallbacks.js sitemap`
// regenerates ONLY sitemap.xml — needed by the publish path, which must refresh the sitemap's
// tool <lastmod> from the freshly computed tool-dates.json but must NOT touch llms.txt /
// llms-full.txt: those carry a "Last updated: <today>" stamp, so regenerating them on every
// publish would make the published tree change every single day (a deployment per day for
// no content change). BUG-469.
const WANT = process.argv.slice(2);
const jobs = [
  ['functions/sitemap.xml.js', 'sitemap.xml'],
  ['functions/llms.txt.js', 'llms.txt'],
  ['functions/llms-full.txt.js', 'llms-full.txt'],
].filter(([, out]) => WANT.length === 0 || WANT.includes(out) || WANT.includes(out.replace(/\.xml$/, '')));
if (!jobs.length) throw new Error('nothing to regenerate: ' + WANT.join(', '));

const outputs = {};
for (const [fn, out] of jobs) {
  const body = await runFn(fn);
  if (!body.includes('/tools/' + last + '/')) {
    throw new Error(out + ': newest manifest slug "' + last + '" missing from regenerated output');
  }
  outputs[out] = body;
  fs.writeFileSync(path.join(ROOT, out), body);
  console.log('[regen] ' + out + ': ' + body.length + ' bytes');
}

let summary = slugs.length + ' tools in manifest';
if (outputs['sitemap.xml']) {
  const locs = new Set([...outputs['sitemap.xml'].matchAll(/<loc>(.*?)<\/loc>/g)].map((m) => m[1]));
  const toolCount = [...locs].filter((u) => /\/tools\/[a-z0-9-]+\/?$/.test(u)).length;
  if (toolCount < slugs.length) {
    throw new Error('sitemap has ' + toolCount + ' /tool/ URLs, manifest has ' + slugs.length);
  }
  summary += ', sitemap ' + locs.size + ' URLs';
}
if (outputs['llms-full.txt']) {
  const fullEntries = outputs['llms-full.txt'].split('\n').filter((l) => /\/tools\/[a-z0-9-]+\/\.md/.test(l)).length;
  if (fullEntries < slugs.length) {
    throw new Error('llms-full.txt has ' + fullEntries + ' tool entries, manifest has ' + slugs.length);
  }
  summary += ', llms-full ' + fullEntries + ' entries';
}
console.log('[regen] asserted: ' + summary + ', newest slug "' + last + '" present in the regenerated output');
